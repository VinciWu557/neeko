//! `system_notify` 主题的共享类型 —— 两条平台腿**唯一**的类型来源。
//!
//! 为什么单独成文件：`macos.rs` 与 `default.rs` 永不同时编译（`mod.rs` 按 `cfg` 二选一），
//! 各自写一份同名别名时**任何一侧漂移都编译通过**（例如只给一条腿去掉 `Send + Sync`）——
//! 典型的「不可见失败域」。放进本文件后别名只实例化一次，两条腿都引用它，漂移不再可能。
//!
//! 同目录 `watch_backend/types.rs` 是同一形态的先例。

/// 点击回流回调：平台层在用户点击系统通知时**只把深链原串**交回给通知域。
///
/// `Send + Sync` 是硬要求而非顺手加的：回调被存进 `static OnceLock`（`macos.rs`），
/// 必须满足 `Sync` 才能跨线程读；`didReceive` 在 ObjC 主线程回调里执行，注册来自任意线程，
/// 故两侧都要求。
///
/// 平台层刻意不认识「会话 / 路由」语义 —— 它只透传字符串，解释权在通知域（`reflow` 路由表）。
pub type ClickHandler = Box<dyn Fn(&str) + Send + Sync>;
