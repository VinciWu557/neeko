/// Identifies an agent kind. `custom` covers user-defined commands.
/// 会话持久化用（ResumeCursor.agent_kind）。
#[derive(Clone, Debug, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]
pub enum AgentKind {
    /// opencode agent.
    Opencode,
    /// claude-code agent.
    ClaudeCode,
    /// gemini agent.
    Gemini,
    /// codex agent.
    Codex,
    /// qoder agent.
    Qoder,
    /// codebuddy agent.
    Codebuddy,
    /// User-defined custom agent（含 mockAgent 等未枚举 id）。
    Custom,
}

impl AgentKind {
    /// Map an agent id (as registered in `AgentManager`) to a kind.
    #[must_use]
    pub fn from_agent_id(agent_id: &str) -> Self {
        match agent_id {
            "opencode" => Self::Opencode,
            "claude-code" => Self::ClaudeCode,
            "gemini" => Self::Gemini,
            "codex" => Self::Codex,
            "qoder" => Self::Qoder,
            "codebuddy" => Self::Codebuddy,
            _ => Self::Custom,
        }
    }
}

/// Build the adapter for an agent from its `AgentConfig`。
///
/// 分派依据 `config.chat`（CHAT 能力数据，自包含启动方式，零 id 特判）：
/// - `None` → 该 agent 无 CHAT 能力（返回 `Unsupported`）；
/// - `Mock` → [`AcpAdapter::mock`]（进程内，无子进程）；
/// - `Acp { args }` → [`AcpAdapter`]（`command + args` 启动，opencode 的
///   `["opencode","acp"]` 由内置定义提供）；
/// - `Serve` → [`ServeAdapter`]（opencode serve 的 REST + SSE 传输）；
/// - `Jsonl` → [`DeepSeekHarnessAdapter`]（stdio JSON-Lines）；
/// - `PiRpc` → [`PiRpcAdapter`]（pi 的私有 `--mode rpc` 协议，单进程）。
pub fn adapter_for(config: &AgentConfig) -> Result<Box<dyn AgentAdapter>, AppError> {
    match &config.chat {
        None => Err(AppError::Unsupported(format!(
            "agent '{}' has no CHAT capability (terminal/headless only)",
            config.id
        ))),
        Some(ChatStart::Mock) => Ok(Box::new(AcpAdapter::mock())),
        Some(ChatStart::Acp { args }) => {
            // `chat_cmd_vec()` 已含 chat 专用可执行文件与参数；`ChatStart::Acp`
            // 的 `args` 是传输级附加（如 opencode 的 `["acp"]`），语义不同，仍追加。
            let mut cmd = config.chat_cmd_vec();
            cmd.extend(args.iter().cloned());
            Ok(Box::new(AcpAdapter::new(cmd)))
        }
        Some(ChatStart::Serve) => Ok(Box::new(ServeAdapter::new())),
        Some(ChatStart::Jsonl) => Ok(Box::new(DeepSeekHarnessAdapter::new(config.chat_cmd_vec()))),
        Some(ChatStart::PiRpc) => Ok(Box::new(pi_rpc::PiRpcAdapter::new(config.chat_cmd_vec()))),
    }
}

/// Binds a session to its working context (A4 — protocolised G4).
#[derive(Clone, Debug)]
pub struct AgentContext {
    /// Agent identifier（真实 id，来自 AgentManager；adapter 用于 SessionStart.agent）。
    pub agent_id: String,
    /// Opaque session identifier (generated by the command layer; must match
    /// the id used in events and the session registry).
    pub session_id: String,
    /// Project identifier.
    pub project_id: String,
    /// Human-readable project name.
    pub project_name: String,
    /// Execution environment: `local` | `wsl` | `ssh`.
    pub env: String,
    /// Skill IDs enabled for this session.
    pub skills: Vec<String>,
    /// File paths attached as context.
    pub files: Vec<String>,
    /// Approval mode: `auto` | `confirm`.
    pub mode: String,
    /// The user's prompt for this turn.
    pub prompt: String,
    /// Model ID selected by the user (per-session / per-turn). `None` → agent default.
    pub model_id: Option<String>,
}

/// How an agent session is obtained (IO shape axis, A1/A5). The trait stays
/// transport-agnostic; each adapter picks Spawn / Connect / Serve internally.
#[async_trait]
pub trait AgentAdapter: Send + Sync {
    /// Returns the agent kind this adapter handles.
    fn kind(&self) -> AgentKind;
    /// Create a session bound to `ctx`. Spawns or connects internally.
    async fn create(&self, ctx: &AgentContext) -> Result<Box<dyn AgentSession>, AppError>;
    /// Resume an existing native session (from the agent's own persisted
    /// storage, e.g. opencode's SQLite or claude-code's JSONL) as a live chat.
    ///
    /// Default: unsupported. Adapters opt in by overriding this plus
    /// [`AgentAdapter::supports_chat_resume`] — new agents never force changes
    /// onto callers (OCP).
    async fn resume(
        &self,
        ctx: &AgentContext,
        native_session_id: &str,
    ) -> Result<Box<dyn AgentSession>, AppError> {
        let _ = ctx;
        Err(AppError::Agent(format!(
            "agent {:?} does not support chat resume (native session {native_session_id})",
            self.kind()
        )))
    }
    /// Whether this adapter can resume a native session as a live chat.
    /// Drives frontend entry visibility (Chat tab list / Histor panel action).
    fn supports_chat_resume(&self) -> bool {
        false
    }
    /// List the models this agent offers, **without** starting a session.
    ///
    /// Default: fall back to the command the agent declares in
    /// [`AgentConfig::model_list_args`]; `Unsupported` when there is none.
    ///
    /// # 为什么这是**唯一**会话外目录入口
    ///
    /// 它是 `AgentAdapter` 上可覆盖的方法，因此「这个 transport 能不能在会
    /// 话外列模型」是一个**局部决策**：opencode 覆盖它（`models --verbose`），
    /// ACP / Pi 不覆盖（它们的列表只存在于会话的 `configOptions` 里，协议没有
    /// 独立的列模型方法）。
    ///
    /// 早先 `list_agent_models` 绕过本方法直接读 `model_list_args`，导致：
    /// ① 本方法与 `ServeAdapter` 的覆盖一起变成死代码；② opencode 的
    /// `models --verbose` 快速路径（它的 `model_list_args` 为 `None`）永远走
    /// 不到，`per-turn` 传输的模型列表恒为空。
    ///
    /// Returning `Err` means "supported but the command failed"; typing it as
    /// `Result` rather than an empty `Vec` keeps the two distinguishable
    /// (an empty list is a legitimate answer, a failure is not).
    async fn list_models(&self, config: &AgentConfig) -> Result<Vec<ModelInfo>, AppError> {
        crate::agent::model_discovery::list_models_by_command(config).await
    }

    /// 本 adapter 是否能选模型（会话内配置项 **或** 每轮请求参数）。
    ///
    /// Driven from [`Self::chat_capabilities`] —— 这里**故意不是**可直接覆盖的
    /// 声明点：能选模型这件事已经在能力快照里表态，再开一个 override 就等于又
    /// 造了一份可以与之矛盾的真相（P1 的形态）。
    ///
    /// 影响 [`ModelCatalogResult::SessionScoped`] 与 [`ModelCatalogResult::Unsupported`]
    /// 的区分：会话外拿不到目录时，能选就回 `SessionScoped`。
    ///
    /// **不要**拿它当「禁止 CLI 目录」的判据 —— `PerTurn`（opencode serve）也
    /// 为真，而它的 id 本来就是 `provider/model` 复合串（`model_slug_split` 就是
    /// 按这个形状拆的），禁掉目录会让它的模型列表恒空。互斥判据是
    /// [`Self::supports_session_config`]。
    fn supports_model_selection(&self) -> bool {
        self.chat_capabilities().config.shows_controls()
    }

    /// 本 `(agent, 传输)` 组合的**完整能力快照**。
    ///
    /// # 为什么必须实现，没有默认值
    ///
    /// 默认值会让「新 adapter 忘填」与「明确不支持」不可区分 —— 前者是缺陷，
    /// 后者是设计。没有默认实现时，新增 adapter 必须显式表态；新增**能力字段**
    /// 时所有既有 adapter 的构造点编译失败，强制回答「我支持吗」。
    ///
    /// P1 的成因正是有默认值：`supports_*` 默认 `false` 而
    /// `SessionStart.capabilities` 又被各 adapter 独立硬编码（四个全填
    /// `approvals: true`，包括没有审批实现的 deepseek）。两份声明互不校验。
    fn chat_capabilities(&self) -> ChatCapabilities;

    /// 本传输是否对**会话配置项**做了完整实现。
    ///
    /// 收口旧 `supports_model_selection`：那个名字语义太模糊 —— ACP 为 true 靠
    /// `configOptions`，serve 为 true 靠 HTTP 请求参数，机制完全不同，调用方
    /// 无法据此判断「能不能发 `set_config_option`」。
    fn supports_session_config(&self) -> bool {
        self.chat_capabilities().config.uses_session_config()
    }
}

/// `list_agent_models` 的结果类型。
///
/// 早先返回 `Vec<ModelInfo>`，空数组同时表示「不支持」「执行失败」「还没加载」——
/// 三者对用户是三种完全不同的处境，UI 只能给出一个永久禁用的 "No models"。
#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
#[serde(tag = "kind", rename_all = "kebab-case")]
pub enum ModelCatalogResult {
    /// 拿到列表了（私有命令路径，如 `opencode models --verbose`）。
    Available {
        /// 模型条目。
        models: Vec<crate::common::agent::types::ModelInfo>,
    },
    /// 该 agent 支持模型选择，但列表**只能在会话内**取得。
    ///
    /// ACP 没有独立的「列模型」方法：模型来自 `session/new` 响应的 `configOptions`。
    /// 因此设置页无法预先枚举 —— 这是协议约束，不是缺陷。
    SessionScoped,
    /// 该 agent 不支持模型选择。
    Unsupported,
}

/// 一个 agent 私有的模型目录（「不建会话就列出模型」的快速路径）。
///
/// 只有确实拥有这种命令的适配器才实现；ACP 路径**故意不实现** —— 它的模型来自
/// 会话的 `configOptions`，本来就不该有独立目录。
/// A live, cancelable agent session (A5 — standard adapter shape).
#[async_trait]
pub trait AgentSession: Send {
    /// Pull the next event. `None` means the session ended.
    async fn next(&mut self) -> Option<Result<StreamEvent, AppError>>;
    /// Send a page→agent message (Gate return / input / rebind / cancel).
    async fn send(&mut self, req: SessionRequest) -> Result<(), AppError>;
    /// Stop the pump, then kill the underlying process after a grace period.
    async fn cancel(&mut self);
    /// Opaque resume handle for session restore.
    fn resume_id(&self) -> Option<String>;
    /// Cloneable page→agent request channel for manager routing.
    ///
    /// Adapters whose `send()` writes directly to the child should return
    /// `None`; channel-backed adapters return a clone so the session registry
    /// can route `agent_approve` / `agent_input` / `agent_stream_cancel`
    /// without racing the event pump.
    fn request_channel(&self) -> Option<mpsc::Sender<SessionRequest>> {
        None
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ctx() -> AgentContext {
        AgentContext {
            agent_id: "opencode".into(),
            session_id: "ac_test".into(),
            project_id: "/tmp/demo".into(),
            project_name: "demo".into(),
            env: "local".into(),
            skills: vec![],
            files: vec![],
            mode: "auto".into(),
            prompt: String::new(),
            model_id: None,
        }
    }

    /// 未覆写 resume 的 adapter（AcpAdapter::mock）必须优雅拒绝而非 panic，
    /// 且 supports_chat_resume 默认关闭 —— 驱动前端入口显隐。
    #[tokio::test]
    async fn default_resume_is_unsupported_and_opt_in() {
        let adapter = AcpAdapter::mock();
        assert!(!adapter.supports_chat_resume());
        let msg = match adapter.resume(&ctx(), "ses_native_1").await {
            Err(e) => format!("{e:?}"),
            Ok(_) => panic!("default resume must return Err, not a session"),
        };
        assert!(
            msg.contains("does not support chat resume"),
            "error should explain resume unsupported: {msg}"
        );
    }

    /// **单一声明点护栏**：`AgentAdapter` 的 adapter 实现不得覆写
    /// `supports_model_selection`。
    ///
    /// 这个方法曾经是可单独 override 的声明点，与 `chat_capabilities().config`
    /// 构成两份可互相矛盾的真相（P1）。现在它由能力快照派生，旧 override 已删。
    /// 这条用例扫 adapter 实现文件，防止它被重新加回来 —— 那种回退不会编译报错，
    /// 只会让某个传输静默地“能选模型但列表是 SessionScoped”。
    ///
    /// 变异验证：在任一 adapter 里恢复 `fn supports_model_selection` → 本用例红。
    #[test]
    fn adapters_do_not_redeclare_model_selection() {
        let dir = concat!(env!("CARGO_MANIFEST_DIR"), "/src/agent/chat/adapter");
        let mut checked = 0usize;
        let mut offenders = Vec::new();
        let mut stack = vec![std::path::PathBuf::from(dir)];
        while let Some(path) = stack.pop() {
            for entry in std::fs::read_dir(&path).expect("read adapter dir") {
                let entry = entry.expect("dir entry");
                let p = entry.path();
                if p.is_dir() {
                    stack.push(p);
                    continue;
                }
                if p.extension().and_then(|e| e.to_str()) != Some("rs") {
                    continue;
                }
                // `adapter.rs` 是声明点本身，允许出现。
                if p.file_name().and_then(|n| n.to_str()) == Some("adapter.rs") {
                    continue;
                }
                let src = std::fs::read_to_string(&p).expect("read adapter source");
                checked += 1;
                if src.contains("fn supports_model_selection") {
                    offenders.push(p.display().to_string());
                }
            }
        }
        assert!(
            checked > 0,
            "scanner found no adapter files (path drifted?)"
        );
        assert!(
            offenders.is_empty(),
            "supports_model_selection must be derived from chat_capabilities(), \
             not overridden in: {offenders:?}"
        );
    }
}

#[cfg(test)]
mod adapter_for_tests {
    use super::*;

    fn cfg(chat: ChatStart) -> AgentConfig {
        AgentConfig {
            id: "t".into(),
            name: "T".into(),
            command: "cli".into(),
            args: vec!["--tui".into()],
            chat: Some(chat),
            ..Default::default()
        }
    }

    /// `adapter_for` 确实能构造出适配器（含 PiRpc / Jsonl 两条 chat_cmd_vec 路径）。
    #[test]
    fn builds_an_adapter_for_every_chat_transport() {
        for chat in [
            ChatStart::Mock,
            ChatStart::Serve,
            ChatStart::Jsonl,
            ChatStart::PiRpc,
            ChatStart::Acp {
                args: vec!["acp".into()],
            },
        ] {
            assert!(adapter_for(&cfg(chat.clone())).is_ok(), "{chat:?}");
        }
    }

    /// **静态护栏**：chat 分支必须用 `chat_cmd_vec()`，不能回退到 CLI 的 `cmd_vec()`。
    ///
    /// 变异验证：把 `PiRpcAdapter::new(config.chat_cmd_vec())` 改回
    /// `config.cmd_vec()` → 本用例红。回退的后果是 `chat_command` 覆盖静默失效
    /// —— 用户配了 `pi-acp`，实际仍 spawn `pi`，且没有任何报错。
    #[test]
    fn chat_branches_use_the_chat_command_vector() {
        let src = std::fs::read_to_string(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/src/agent/chat/adapter.rs"
        ))
        .expect("read adapter.rs");
        // 只看生产代码：测试块里的字符串会自我命中。
        let production = src
            .split("#[cfg(test)]")
            .next()
            .expect("production section");

        assert!(
            production.contains("config.chat_cmd_vec()"),
            "adapter_for must call chat_cmd_vec() so chat_command takes effect"
        );
        for stale in [
            "DeepSeekHarnessAdapter::new(config.cmd_vec())",
            "pi_rpc::PiRpcAdapter::new(config.cmd_vec())",
        ] {
            assert!(!production.contains(stale), "found stale CLI form: {stale}");
        }
    }
}
