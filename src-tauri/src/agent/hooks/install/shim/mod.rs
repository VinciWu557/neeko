//! **落盘层**：所有"写入磁盘"的实现点，共同不变量是
//! **原子替换 + 保留原权限位**（都经 `platform::private_file::write_atomic_preserving_mode`）。
//!
//! # 为什么这三者在一起（而不是按"写谁"分组）
//!
//! 两个子域都要写文件，但**写入契约是同一套**：
//!
//! | 单元 | 写什么 | 归属判据 |
//! | --- | --- | --- |
//! | `ownership` | （不写）只回答「这是不是我们装的」 | 首行标记 + 内容寻址版本位 |
//! | `io` | 受管 shim 文件（`neeko-status.*`） | 写前问 `ownership`，他人资产则拒绝 |
//! | `config_io` | **用户既有配置**（`settings.json` / `config.toml`） | 不改归属，只做定点改写 |
//!
//! 分成三份而不是一份，是因为变化频率与测试方式不同：判据是纯逻辑（纯 tempdir）、
//! shim 落盘要验幂等/原子性、用户配置落盘要验**权限位继承**（Unix 专属断言）。
//!
//! # 为什么目录名是 `shim` 而不是 `persist`
//!
//! 历史名。真实伞名是「持久化」—— `config_io` 并不写 shim。若重命名，
//! 改动面是 3 个 `use` 路径 + 1 个 `mod` 声明，属可做但非必要的清理；
//! 此处以文档澄清替代重命名，避免把已经稳定的目录再动一次。

pub mod config_io;
pub mod io;
pub mod ownership;
